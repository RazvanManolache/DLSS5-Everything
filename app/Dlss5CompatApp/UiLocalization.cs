    static readonly UiLanguage[] Catalog = JsonSerializer.Deserialize<UiLanguage[]>(LocaleJson)!;
    public static IReadOnlyList<UiLanguage> Languages { get; } = Array.AsReadOnly(Catalog);
    readonly UiLanguage _language;
    public UiLocalization(string? code = "en") => _language = Catalog.FirstOrDefault(l => l.Code == code) ?? Catalog[0];
    public string Code => _language.Code;
    public bool RightToLeft => _language.RightToLeft;
    public bool IsPartial => Code != "en";
    public static bool Supports(string? code) => Catalog.Any(l => l.Code == code);
    public string this[string key] => _language.Strings.GetValueOrDefault(key) ?? Catalog[0].Strings.GetValueOrDefault(key) ?? key;
    public bool UsesFallback(string key) => !_language.Strings.ContainsKey(key);
    public string CoverageText => this[IsPartial ? "translationCoverage" : "fullEnglish"];

